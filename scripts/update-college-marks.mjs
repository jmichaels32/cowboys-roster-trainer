#!/usr/bin/env node

import { spawnSync } from "node:child_process";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import vm from "node:vm";

const projectRoot = resolve(new URL("..", import.meta.url).pathname);
const rosterSources = await Promise.all([
  readFile(resolve(projectRoot, "data/roster.js"), "utf8"),
  readFile(resolve(projectRoot, "data/patriots-roster.js"), "utf8"),
]);
const rosterContext = { window: {} };
vm.createContext(rosterContext);
rosterSources.forEach((source) => vm.runInContext(source, rosterContext));

const colleges = [...new Set([
  ...rosterContext.window.COWBOYS_ROSTER.players,
  ...rosterContext.window.PATRIOTS_ROSTER.players,
].map((player) => player.college).filter(Boolean))].sort();
const aliases = {
  "Jackson State University": "Jackson State",
  "Louisiana-Lafayette": "Louisiana",
  Mississippi: "Ole Miss",
  "University of South Florida": "South Florida",
};
const directLogos = {
  "Loughborough (UK)": "https://www.lboro.ac.uk/web-assets/shared/favicon/favicon-96x96.png",
};
const teamResponse = await fetch(
  "https://site.api.espn.com/apis/site/v2/sports/football/college-football/teams?limit=1000",
);
if (!teamResponse.ok) throw new Error(`ESPN team request failed: ${teamResponse.status}`);
const teamPayload = await teamResponse.json();
const teams = (teamPayload.sports?.[0]?.leagues?.[0]?.teams ?? []).map(({ team }) => team);
const outputDirectory = resolve(projectRoot, "assets/college-marks");
await mkdir(outputDirectory, { recursive: true });

function normalize(value) {
  return value.toLowerCase().replace(/university|the|[^a-z0-9]/g, "");
}

function slug(value) {
  return value
    .toLowerCase()
    .normalize("NFKD")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
}

function monogram(value) {
  const words = value.replace(/\([^)]*\)/g, "").split(/[^A-Za-z0-9]+/).filter(Boolean);
  return (words.length > 1 ? words.map((word) => word[0]).join("") : words[0]?.slice(0, 2) ?? "C").slice(0, 3).toUpperCase();
}

const marks = {};
for (const college of colleges) {
  const lookup = aliases[college] ?? college;
  const team = teams.find(
    (candidate) =>
      normalize(candidate.location ?? "") === normalize(lookup) ||
      normalize(candidate.displayName ?? "") === normalize(lookup),
  );
  const logo = directLogos[college] ?? team?.logos?.find(({ href }) => href.includes("/500/") && href.endsWith(".png"))?.href;
  if (!logo) {
    marks[college] = { label: monogram(college) };
    continue;
  }

  const filename = `${slug(college)}.png`;
  const filePath = resolve(outputDirectory, filename);
  const logoResponse = await fetch(logo);
  if (!logoResponse.ok) throw new Error(`Logo request failed for ${college}: ${logoResponse.status}`);
  await writeFile(filePath, Buffer.from(await logoResponse.arrayBuffer()));
  spawnSync("sips", ["-Z", "96", filePath], { stdio: "ignore" });
  marks[college] = { src: `assets/college-marks/${filename}`, label: monogram(college) };
}

const generated = `// Generated by scripts/update-college-marks.mjs from ESPN college team identities.\nwindow.COLLEGE_MARKS = ${JSON.stringify(marks, null, 2)};\n`;
await writeFile(resolve(projectRoot, "data/college-marks.js"), generated);
console.log(`Cached ${Object.values(marks).filter(({ src }) => src).length} college marks; ${Object.values(marks).filter(({ src }) => !src).length} text fallback.`);
